export const IconMap: Record<string, React.ComponentType<{ className?: string; style?: React.CSSProperties }>> = {
  rechnung: FileText,
  kopfhoerer: Headphones,
  kalender: Calendar,
  code: Code,
  aktentasche: Briefcase,
  megafon: Megaphone,
  roboter: Bot,
  suche: Search,
  cache: Database,
  library: BookOpen,
  web: Globe,
  ki: Cpu,
  blatt: Leaf,
};

export function getAgentIcon(iconName?: string): React.ComponentType<{ className?: string; style?: React.CSSProperties }> {
  if (!iconName) return Bot;
  const key = iconName.toLowerCase().trim();
  return IconMap[key] || Bot;
}

